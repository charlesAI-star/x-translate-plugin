function yamlValue(value) {
  return JSON.stringify(String(value ?? ''));
}

function quoteBlock(text) {
  return String(text || '')
    .split('\n')
    .map((line) => `> ${line}`)
    .join('\n');
}

function frontmatter(entry) {
  const tags = (entry.tags || []).map((tag) => `  - ${yamlValue(tag)}`).join('\n');
  return [
    '---',
    `id: ${yamlValue(entry.id)}`,
    `source: ${yamlValue(entry.source.url)}`,
    `type: ${yamlValue(entry.source.type)}`,
    `author: ${yamlValue([entry.source.author_name, entry.source.author_handle ? `@${entry.source.author_handle}` : ''].filter(Boolean).join(' '))}`,
    `published: ${yamlValue(entry.source.published_at || '')}`,
    `captured: ${yamlValue(entry.source.captured_at || '')}`,
    `category: ${yamlValue([entry.category_l1_name, entry.category_l2_name].filter(Boolean).join(' / '))}`,
    `status: ${yamlValue(entry.status)}`,
    'tags:',
    tags || '  []',
    '---',
    ''
  ].join('\n');
}

export function buildEntryMarkdown(entry) {
  const lines = [frontmatter(entry), `# ${entry.title || '未命名条目'}`, ''];

  if (entry.source.url) {
    lines.push(`**来源**：${entry.source.url}`, '');
  }
  if (entry.summary) {
    lines.push('## AI 摘要', '', entry.summary, '');
  }
  const keyPoints = Array.isArray(entry.analysis?.key_points) ? entry.analysis.key_points : [];
  if (keyPoints.length) {
    lines.push('## 关键要点', '');
    for (const point of keyPoints) lines.push(`- ${point}`);
    lines.push('');
  }
  if (entry.tags?.length) {
    lines.push(`**标签**：${entry.tags.map((tag) => `#${tag}`).join(' ')}`, '');
  }

  const notes = entry.notes || [];
  if (notes.length) {
    lines.push('## 我的想法', '');
    for (const note of notes) {
      lines.push(`### ${formatLocal(note.created_at)}`, '', note.body, '');
    }
  }

  if (entry.content?.text) {
    lines.push('## 原文', '', quoteBlock(entry.content.text), '');
    if (entry.content.truncated) lines.push('> （原文在采集时被截断）', '');
  }

  if (entry.quoted) {
    lines.push('## 引用推文', '');
    const quotedAuthor = [entry.quoted.author?.name, entry.quoted.author?.handle ? `@${entry.quoted.author.handle}` : '']
      .filter(Boolean)
      .join(' ');
    if (quotedAuthor) lines.push(`**${quotedAuthor}**`, '');
    if (entry.quoted.content?.text) lines.push(quoteBlock(entry.quoted.content.text), '');
    if (entry.quoted.url) lines.push(`引用链接：${entry.quoted.url}`, '');
  }

  if (entry.links?.length) {
    lines.push('## 链接', '');
    for (const link of entry.links) lines.push(`- ${link.text ? `${link.text} — ` : ''}${link.url}`);
    lines.push('');
  }

  if (entry.media?.length) {
    lines.push('## 图片', '');
    for (const media of entry.media) {
      if (media.url) lines.push(`- ${media.alt || media.caption || '图片'} — ${media.url}`);
    }
    lines.push('');
  }

  lines.push('<!-- generated by x-knowledge-agent -->', '');
  return lines.join('\n');
}

function resolveWithin(base, ...parts) {
  const root = path.resolve(base);
  const target = path.resolve(root, ...parts);
  const relative = path.relative(root, target);
  if (
    !relative ||
    relative === '..' ||
    relative.startsWith(`..${path.sep}`) ||
    path.isAbsolute(relative)
  ) {
    throw new Error(`导出路径越界：${target}`);
  }
  return target;
}

function entryFilePath(entry) {
  const l1 = safePathPart(entry.category_l1_name || entry.category_l1, '未分类');
  const l2 = entry.category_l2_name ? safePathPart(entry.category_l2_name) : '_';
  return resolveWithin(libraryDir(), l1, l2, `${safeFileId(entry.id)}.md`);
}

export function syncEntryMarkdown(id) {
  const entry = getEntry(id);
  if (!entry) return null;
  const db = getDb();
  const oldPath = entry.markdown_path || null;
  if (entry.deleted_at) {
    if (oldPath && fs.existsSync(oldPath)) {
      try {
        fs.unlinkSync(oldPath);
      } catch {}
    }
    db.prepare('UPDATE entries SET markdown_path = NULL WHERE id = ?').run(String(id));
    return null;
  }
  const target = entryFilePath(entry);
  atomicWrite(target, buildEntryMarkdown(entry));
  if (oldPath && oldPath !== target && fs.existsSync(oldPath)) {
    try {
      fs.unlinkSync(oldPath);
    } catch {}
  }
  db.prepare('UPDATE entries SET markdown_path = ? WHERE id = ?').run(target, String(id));
  return target;
}

export function syncEntries(ids) {
  const out = [];
  for (const id of ids) {
    try {
      const file = syncEntryMarkdown(id);
      if (file) out.push(file);
    } catch (err) {
      console.error(`[markdown] 同步失败 ${id}: ${err.message}`);
    }
  }
  return out;
}

export function syncEntriesForCategory(categoryKey) {
  const rows = getDb()
    .prepare('SELECT id FROM entries WHERE deleted_at IS NULL AND (category_l1 = ? OR category_l2 = ?)')
    .all(String(categoryKey), String(categoryKey));
  return syncEntries(rows.map((row) => row.id));
}

export function syncAllActiveEntries() {
  const rows = getDb().prepare('SELECT id FROM entries WHERE deleted_at IS NULL').all();
  return syncEntries(rows.map((row) => row.id));
}

export function writeReportMarkdown(weekKey, markdown) {
  const dir = reportsDir();
  ensureDir(dir);
  const file = resolveWithin(dir, `${safePathPart(weekKey, 'report')}.md`);
  atomicWrite(file, markdown);
  return file;
}

export function writeSummaryMarkdown(categoryKey, categoryName, markdown) {
  const dir = path.join(libraryDir(), '_summaries');
  ensureDir(dir);
  // 用稳定的分类 key 命名，改名后不会留下旧文件。
  const file = resolveWithin(dir, `${safePathPart(categoryKey, 'summary')}.md`);
  atomicWrite(file, markdown);
  return file;
}

export function writeAllSummaries() {
  const summaries = getCategorySummaries();
  const out = [];
  for (const summary of summaries) {
    out.push(writeSummaryMarkdown(summary.category_key, summary.category_name, summary.content_md));
  }
  return out;
}

function renderInline(text) {
  const parts = String(text ?? '').split(/(`[^`\n]+`)/g);
  return parts
    .map((part) => {
      if (part.startsWith('`') && part.endsWith('`') && part.length >= 2) {
        return `<code>${escapeHtml(part.slice(1, -1))}</code>`;
      }
      let html = escapeHtml(part);
      html = html.replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, (match, label, url) => {
        const rawUrl = url.replace(/&amp;/g, '&');
        if (!isHttpUrl(rawUrl)) return match;
        return `<a href="${url}" target="_blank" rel="noopener noreferrer">${label}</a>`;
      });
      html = html.replace(/\*\*([^*\n]+)\*\*/g, '<strong>$1</strong>');
      html = html.replace(/\*([^*\n]+)\*/g, '<em>$1</em>');
      return html;
    })
    .join('');
}

export function renderMarkdownHtml(markdown) {
  const lines = String(markdown || '').replace(/\r\n/g, '\n').split('\n');
  const html = [];
  let i = 0;
  let paragraph = [];
  let list = null;

  const flushParagraph = () => {
    if (paragraph.length) {
      html.push(`<p>${renderInline(paragraph.join(' '))}</p>`);
      paragraph = [];
    }
  };
  const flushList = () => {
    if (list) {
      html.push(`<${list.type}>${list.items.map((item) => `<li>${renderInline(item)}</li>`).join('')}</${list.type}>`);
      list = null;
    }
  };

  while (i < lines.length) {
    const line = lines[i];

    if (/^```/.test(line.trim())) {
      flushParagraph();
      flushList();
      const code = [];
      i += 1;
      while (i < lines.length && !/^```/.test(lines[i].trim())) {
        code.push(lines[i]);
        i += 1;
      }
      i += 1;
      html.push(`<pre><code>${escapeHtml(code.join('\n'))}</code></pre>`);
      continue;
    }

    if (!line.trim()) {
      flushParagraph();
      flushList();
      i += 1;
      continue;
    }

    const heading = line.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      flushParagraph();
      flushList();
      const level = heading[1].length;
      html.push(`<h${level}>${renderInline(heading[2])}</h${level}>`);
      i += 1;
      continue;
    }

    if (/^---+$/.test(line.trim())) {
      flushParagraph();
      flushList();
      html.push('<hr>');
      i += 1;
      continue;
    }

    if (/^>\s?/.test(line)) {
      flushParagraph();
      flushList();
      const quote = [];
      while (i < lines.length && /^>\s?/.test(lines[i])) {
        quote.push(lines[i].replace(/^>\s?/, ''));
        i += 1;
      }
      html.push(`<blockquote>${quote.map((q) => (q ? `<p>${renderInline(q)}</p>` : '')).join('')}</blockquote>`);
      continue;
    }

    const unordered = line.match(/^\s*[-*+]\s+(.*)$/);
    const ordered = line.match(/^\s*\d+[.)]\s+(.*)$/);
    if (unordered || ordered) {
      flushParagraph();
      const type = unordered ? 'ul' : 'ol';
      if (!list || list.type !== type) {
        flushList();
        list = { type, items: [] };
      }
      list.items.push((unordered || ordered)[1]);
      i += 1;
      continue;
    }

    flushList();
    paragraph.push(line.trim());
    i += 1;
  }
  flushParagraph();
  flushList();
  return html.join('\n');
}

export function renderEntryForApi(entry) {
  if (!entry) return null;
  return {
    ...entry,
    notes: (entry.notes || []).map((note) => ({
      ...note,
      body_html: renderMarkdownHtml(note.body)
    })),
    l1_summary: entry.l1_summary
      ? { ...entry.l1_summary, content_html: renderMarkdownHtml(entry.l1_summary.content_md) }
      : null
  };
}

export function renderSummaryForApi(summary) {
  return summary
    ? { ...summary, content_html: renderMarkdownHtml(summary.content_md) }
    : null;
}

export function renderReportForApi(run) {
  if (!run) return null;
  return {
    ...run,
    report_html: run.report_md ? renderMarkdownHtml(run.report_md) : ''
  };
}

export function markdownPreview(text, max = 160) {
  return truncate(String(text || '').replace(/\s+/g, ' ').trim(), max);
}

export function configLibraryPath() {
  return libraryDir(loadConfig());
}
